/** @param {string} code — ISO 2-letter code or "OTHER" */
function getCountryPack(code) {
  return COUNTRY_PACKS[code] || COUNTRY_PACKS.OTHER;
}

function getAllCountryPacks() {
  return Object.values(COUNTRY_PACKS);
}

/** Resolve country display name → pack code (for backward compat with setup wizard sending "Pakistan" instead of "PK") */
function getCountryCodeFromName(name) {
  if (!name) return "OTHER";
  const upper = name.toUpperCase();
  // Direct code match
  if (COUNTRY_PACKS[upper]) return upper;
  // Name match
  for (const pack of Object.values(COUNTRY_PACKS)) {
    if (pack.name.toLowerCase() === name.toLowerCase()) return pack.code;
  }
  return "OTHER";
}

